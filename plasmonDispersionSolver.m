function [k_p, delta, Kall, deltas, idx, a] = plasmonDispersionSolver(omega, sigma, e1, e2)
% ВЫВОД:    волновое число, невязка
%           4 кандидата в волновое число, их невзяки, номер выбранного кандидата, 4 корня полинома
% ВВОД:     частота, поверхностная проводимость, проницаемости двух сред
    
    c = 29979245800; % speed of light in cm/s 
    
    s = sigma/c; 
    
    Coef(1) = 256*pi^4*s^4;
    
    Coef(2) = -32*(16*pi^4*e1*s^4 + 16*pi^4*e2*s^4 - pi^2*e1^2*s^2 - pi^2*e2^2*s^2);
    
    Coef(3) = 256*pi^4*e1^2*s^4 + 1024*pi^4*e1*e2*s^4 + 256*pi^4*e2^2*s^4 - 32*pi^2*e1^3*s^2 ...
        - 64*pi^2*e1^2*e2*s^2 - 64*pi^2*e1*e2^2*s^2 - 32*pi^2*e2^3*s^2 + e1^4 - 2*e1^2*e2^2 + e2^4;
    
    Coef(4) = -2*(256*pi^4*e1^2*e2*s^4 + 256*pi^4*e1*e2^2*s^4 - 32*pi^2*e1^3*e2*s^2 ...
        - 32*pi^2*e1^2*e2^2*s^2 - 32*pi^2*e1*e2^3*s^2 + e1^4*e2 - e1^3*e2^2 - e1^2*e2^3 + e1*e2^4);
    
    Coef(5) = 256*pi^4*e1^2*e2^2*s^4 - 32*pi^2*e1^3*e2^2*s^2 - 32*pi^2*e1^2*e2^3*s^2 + e1^4*e2^2 ...
        - 2*e1^3*e2^3 + e1^2*e2^4;

    a = roots(Coef);                                            % находим корни полинома

    deltas = abs((e1./sqrt(e1-a) + e2./sqrt(e2-a)) - 4*pi*s);   % невязка
    % deltas = (e1./abs(sqrt(e1-a)) + e2./abs(sqrt(e2-a)) - 4*pi*s);   % невязка
    [delta, idx] = min(deltas);                                 % минимальная невязка
    Kall = sqrt(a)*omega/c;                                     % находим 4 волновых числа
    k_p = Kall(idx);                                         % выбираем с минимальной невязкой

end

